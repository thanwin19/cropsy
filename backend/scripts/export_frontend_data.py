"""Export the village dataset to the frontend so the map, selectors and panels all read the same 120 parcels.

Writes (inside frontend/):
  src/data/villageParcels.generated.ts        typed array used by THEN_MALAI_PARCELS
  public/data/then_malai/village_parcels.geojson   static fallback when /api/parcels is unreachable
Run after build_dataset.py:  python backend/scripts/export_frontend_data.py
Then compute horizon profiles for every parcel:  (in the frontend)  npm run horizons:write
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FE = ROOT / "frontend"   # the Lovable-built front end (TanStack Start)
DATA = ROOT / "backend" / "data"

# Hand-set values already used by the app for the 16 anchor parcels (ridgeKm, ridgeM). Kept verbatim.
ANCHOR_RIDGE = {
    "TM-01": (4.0, 685), "TM-02": (4.5, 650), "TM-03": (5.0, 600), "TM-04": (5.5, 580), "TM-05": (6.0, 560),
    "TM-06": (4.2, 670), "TM-07": (3.8, 680), "TM-08": (3.9, 675), "TM-09": (4.8, 620), "TM-10": (5.4, 580),
    "TM-11": (6.2, 550), "TM-12": (3.5, 710), "TM-13": (5.6, 570), "TM-14": (6.3, 540), "TM-15": (6.8, 530),
    "TM-16": (6.9, 525),
}


def ridge_for(pid, lat, lon, anchors):
    if pid in ANCHOR_RIDGE:
        return ANCHOR_RIDGE[pid]
    near = sorted(anchors, key=lambda a: math.hypot(a["lat"] - lat, (a["lon"] - lon) * 0.99))[:3]
    w = [1 / max(math.hypot(a["lat"] - lat, a["lon"] - lon), 1e-4) for a in near]
    km = sum(wi * ANCHOR_RIDGE[a["id"]][0] for wi, a in zip(w, near)) / sum(w)
    m = sum(wi * ANCHOR_RIDGE[a["id"]][1] for wi, a in zip(w, near)) / sum(w)
    return round(km, 1), round(m / 5) * 5


def main():
    gj = json.loads((DATA / "village_parcels.geojson").read_text(encoding="utf-8"))
    full = {p["parcel_id"]: p for p in json.loads((DATA / "parcels.json").read_text(encoding="utf-8"))}
    anchors = []
    for f in gj["features"]:
        if f["properties"]["anchor"]:
            anchors.append({"id": f["id"], "lat": f["properties"]["lat"], "lon": f["properties"]["lon"]})

    rows = []
    for f in gj["features"]:
        pr = f["properties"]
        pid = f["id"]
        rec = full[pid]
        ring = f["geometry"]["coordinates"][0][:-1]
        rk, rm = ridge_for(pid, pr["lat"], pr["lon"], anchors)
        rows.append({
            "id": pid, "lat": pr["lat"], "lon": pr["lon"], "elevM": round(pr["elevation_m"]),
            "crop": pr["crop"], "ridgeKm": rk, "ridgeM": rm,
            "coords": [[round(la, 6), round(lo, 6)] for lo, la in ring],
            "anchor": pr["anchor"], "zone": pr["zone"], "variety": pr["variety"], "stage": pr["stage"],
            "daysAfterPlanting": pr["days_after_planting"], "plantingDate": pr["planting_date"],
            "areaHa": pr["area_ha"], "owner": pr["owner"], "pattaNo": pr["patta_no"],
            "issueCode": pr["issue_code"], "issue": pr["issue"], "severity": pr["severity"], "kind": pr["kind"],
            "soilTexture": pr["soil_texture"], "soilPh": pr["soil_ph"], "drainageRisk": pr["drainage_risk"],
            "irrigationDaysAgo": rec["management"]["days_since_last_irrigation"],
            "fertilizerDaysAgo": rec["management"]["days_since_last_fertilizer"],
            "name": rec["field_name"], "dataSource": "dummy",
        })

    ts = [
        "// GENERATED by backend/scripts/export_frontend_data.py - do not edit by hand.",
        "// Then Malai demo village: 16 anchor parcels (real coordinates/soil/terrain) + generated parcels. All",
        "// owner/crop/issue values are DUMMY. ridgeKm/ridgeM are hand-set for anchors, interpolated (approximate) otherwise.",
        "",
        "export interface VillageParcel {",
        "  id: string; lat: number; lon: number; elevM: number; crop: string; ridgeKm: number; ridgeM: number;",
        "  coords: [number, number][]; anchor: boolean; zone: \"valley\" | \"terrace\" | \"foothill\"; variety: string;",
        "  stage: string; daysAfterPlanting: number; plantingDate: string; areaHa: number; owner: string; pattaNo: string;",
        "  issueCode: string; issue: string; severity: string; kind: string; soilTexture: string; soilPh: number;",
        "  drainageRisk: string; irrigationDaysAgo: number; fertilizerDaysAgo: number; name: string; dataSource: \"dummy\";",
        "}",
        "",
        "export const VILLAGE_PARCELS: VillageParcel[] = " + json.dumps(rows, indent=1, ensure_ascii=False) + ";",
        "",
    ]
    out = FE / "src" / "data"
    out.mkdir(parents=True, exist_ok=True)
    (out / "villageParcels.generated.ts").write_text("\n".join(ts), encoding="utf-8")

    pub = FE / "public" / "data" / "then_malai"
    (pub / "village_parcels.geojson").write_text(json.dumps(gj, ensure_ascii=False), encoding="utf-8")
    print(f"{len(rows)} parcels -> {out / 'villageParcels.generated.ts'}")
    print(f"geojson -> {pub / 'village_parcels.geojson'}")


if __name__ == "__main__":
    main()
